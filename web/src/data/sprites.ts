/* ========================================================================
   CONVERSIÓN A SVG
   ======================================================================== */

/**
 * Convierte una rejilla en rectángulos SVG.
 *
 * Une los píxeles contiguos del mismo color en un solo `rect`: un sigilo pasa
 * de ~120 rectángulos a ~35. Con 13 sigilos y 39 iconos en la misma página,
 * la diferencia en tamaño de HTML es notable.
 */
export function spriteASvg(filas: Sprite, paleta: readonly string[]): string {
  const piezas: string[] = [];
  filas.forEach((fila, y) => {
    let x = 0;
    while (x < fila.length) {
      const c = fila[x]!;
      if (c === '.') { x++; continue; }
      let n = 1;
      while (x + n < fila.length && fila[x + n] === c) n++;
      const color = paleta[Number(c) - 1] ?? paleta[paleta.length - 1];
      piezas.push(`<rect x="${x}" y="${y}" width="${n}" height="1" fill="${color}"/>`);
      x += n;
    }
  });
  return piezas.join('');
}

/** Busca un sprite por nombre, mire donde mire. */
export function buscarSprite(nombre: string): Sprite | null {
  return SIGILOS[nombre] ?? ICONOS[nombre] ?? null;
}
